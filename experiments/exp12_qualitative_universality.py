#!/usr/bin/env python3
"""
Test 12: full universality of the 4 cells across the 8 options.

Uses the star_or_plus0 convention (S3-equivariant for all 8 options,
by Test 9). Compares nonempty cells per k across all options.
"""

from sw.common import classify, chain_to_word, load_canonical

# k_max per option, tuned by alphabet size
OPTIONS = {
    1: 8, 2: 8, 3: 8, 4: 5,   # already generated by Test 3
    5: 8, 6: 8, 7: 5, 8: 5,   # new; generated by this test
}

CELLS = ["PP", "Pp", "pP", "Ap"]


def table_for_option(option, k_max):
    rows = []
    for k in range(2, k_max + 1):
        try:
            chains = load_canonical(option, k)
        except Exception as e:
            print(f"  warning: option {option} k={k}: {e}")
            continue
        counts = {c: 0 for c in CELLS}
        for ch in chains:
            w = chain_to_word(ch, convention="star_or_plus0")
            counts[classify(w)] += 1
        rows.append({
            "k": k, "n": len(chains),
            "nv": sum(1 for v in counts.values() if v),
            "cells": dict(counts),
        })
    return rows


if __name__ == "__main__":
    print("=" * 100)
    print("TEST 12 - Universality of the 4 cells across the 8 options")
    print("=" * 100)
    print()
    print("Convention: star_or_plus0 (S3-equivariant on all 8 options)")
    print()

    tables = {}
    for option, k_max in OPTIONS.items():
        print(f"### Option {option} (k=2..{k_max})...")
        tables[option] = table_for_option(option, k_max)
        print(f"  {len(tables[option])} levels processed")

    print()
    print("=" * 100)
    print("NONEMPTY CELLS PER OPTION")
    print("=" * 100)
    print()
    print(f"{'k':>3} | " + " | ".join(f"op{o:>1}" for o in OPTIONS))
    print("-" * 60)
    k_global = sorted(set(r["k"] for tab in tables.values() for r in tab))
    for k in k_global:
        parts = []
        for option in OPTIONS:
            row = next((r for r in tables[option] if r["k"] == k), None)
            parts.append(str(row["nv"]) if row else "--")
        print(f"{k:>3} | " + " | ".join(f"{p:>3}" for p in parts))

    print()
    print("=" * 100)
    print("FULL TABLES PER OPTION")
    print("=" * 100)
    for option, tab in tables.items():
        print()
        print(f"-- Option {option} -----------------------------------------")
        print(f"{'k':>3} | {'orb':>6} | {'cells':>6} | "
              f"{'PP':>4} | {'Pp':>4} | {'pP':>4} | {'Ap':>5}")
        print("-" * 60)
        for r in tab:
            print(f"{r['k']:>3} | {r['n']:>6} | {r['nv']:>6} | "
                  f"{r['cells']['PP']:>4} | {r['cells']['Pp']:>4} | "
                  f"{r['cells']['pP']:>4} | {r['cells']['Ap']:>5}")

    print()
    print("=" * 100)
    print("READING")
    print("=" * 100)
    print("""
- If all columns have the same 'cells' value for each k, the
  universality is confirmed across the 8 options.
- If any differs, investigate why (could be the convention or the
  option's alphabet).
""")
