#!/usr/bin/env python3
"""
Test 6: stability of the classification under fibration.

For each transition n -> n+1 (data/fibration/fib_nk_nk+1.tsv),
classify the parent and the child by cell, and build the transition
matrix (4x4).

Question: does the cell of the parent determine the cell of the child?
  - Yes: the classification is stable under stacking.
  - No: there are transitions, and they are interesting for the
    companion paper (canonical augmentation).

Fibration data is generated by caugJAM's scripts/fibration.py. If not
present, this test prints "(no data)" for the missing level.
"""

from collections import Counter

from sw.common import chain_to_word, classify, load_fibration

CELLS = ["PP", "Pp", "pP", "Ap"]


def transition_matrix(n, option=1):
    pairs = load_fibration(option, n)
    if pairs is None:
        return None
    mat = Counter()
    for parent, child in pairs:
        cp = classify(chain_to_word(parent))
        cc = classify(chain_to_word(child))
        mat[(cp, cc)] += 1
    return mat


def print_matrix(n, mat):
    print(f"\nn -> {n + 1}")
    print(" " * 6 + " | " + " | ".join(f"{c:>4}" for c in CELLS) + " | total")
    print("-" * (6 + 4 * 7 + 9))
    for cp in CELLS:
        row = [mat.get((cp, cc), 0) for cc in CELLS]
        total = sum(row)
        if total == 0:
            continue
        print(f"{cp:>6} | " + " | ".join(f"{v:>4}" for v in row) + f" | {total}")


if __name__ == "__main__":
    print("=" * 80)
    print("TEST 6 - Stability of the cell under fibration")
    print("=" * 80)
    print()
    print("Each entry (row, col) = number of parent->child pairs with")
    print("cell(parent) = row and cell(child) = col.")

    for n in range(1, 8):
        mat = transition_matrix(n)
        if mat is None:
            print(f"\nn -> {n + 1}: (no data)")
            continue
        print_matrix(n, mat)

    print()
    print("=" * 80)
    print("READING")
    print("=" * 80)
    print("""
- Diagonal-dominant matrix => the cell is (almost) stable under fibration.
- Rows with entries in several columns => the cell of the parent does not
  determine the cell of the child; there are "transitions" worth
  documenting.
- Empty rows => the cell does not appear at this level.
""")
